function summary = summarize_chj_rejection_results(raw, lambda_grid)
%% Aggregate CHJ replication results into rejection and tuning diagnostics.

if nargin < 2 || isempty(lambda_grid)
    error('summarize_chj_rejection_results:MissingGrid', ...
        'Provide the lambda grid used in the CHJ revision design.');
end

lambda_grid = lambda_grid(:);
lambdaLower = min(lambda_grid);
lambdaUpper = max(lambda_grid);

[G, Tval, horizon_days, region, testType, role, lambda_mode, ...
    ls_endo_rule, ls_exo_rule, exo_grid_type, exo_mode, ...
    covariance_rule, covariance_type, covariance_bandwidth, ...
    covariance_bandwidth_rule, winsor_margin] = findgroups( ...
    raw.Tval, raw.horizon_days, raw.region, raw.testType, raw.role, ...
    raw.lambda_mode, raw.ls_endo_rule, raw.ls_exo_rule, raw.exo_grid_type, ...
    raw.exo_mode, raw.covariance_rule, raw.covariance_type, ...
    raw.covariance_bandwidth, raw.covariance_bandwidth_rule, raw.winsor_margin);

B = splitapply(@numel, raw.p_value, G);
valid_tests = splitapply(@(x) sum(isfinite(x)), raw.p_value, G);

lambda_median = splitapply(@median, raw.lambda, G);
lambda_inference_median = lambda_median;
lambda_p25 = splitapply(@(x) quantile(x, 0.25), raw.lambda, G);
lambda_p75 = splitapply(@(x) quantile(x, 0.75), raw.lambda, G);
lambda_lower_bound_freq = splitapply(@(x) mean(abs(x - lambdaLower) <= 1e-12 * max(1, abs(lambdaLower))), raw.lambda, G);
lambda_upper_bound_freq = splitapply(@(x) mean(abs(x - lambdaUpper) <= 1e-12 * max(1, abs(lambdaUpper))), raw.lambda, G);
if ismember('lambda_fit', raw.Properties.VariableNames)
    lambdaFit = raw.lambda_fit;
else
    lambdaFit = raw.lambda;
end
lambda_fit_median = splitapply(@median, lambdaFit, G);
lambda_fit_lower_bound_freq = splitapply(@(x) mean(abs(x - lambdaLower) <= 1e-12 * max(1, abs(lambdaLower))), lambdaFit, G);
lambda_fit_upper_bound_freq = splitapply(@(x) mean(abs(x - lambdaUpper) <= 1e-12 * max(1, abs(lambdaUpper))), lambdaFit, G);
lambda_changed_freq = splitapply(@(x) mean(x), double(raw.lambda < lambdaFit), G);
lambda_ratio_median = splitapply(@median, raw.lambda ./ lambdaFit, G);
cv_mean_loss = splitapply(@(x) mean(x, 'omitnan'), raw.cv_mean_loss, G);

ls_endo = splitapply(@median, raw.ls_endo, G);
ls_exo_median = splitapply(@median, raw.ls_exo, G);
ls_exo_p25 = splitapply(@(x) quantile(x, 0.25), raw.ls_exo, G);
ls_exo_p75 = splitapply(@(x) quantile(x, 0.75), raw.ls_exo, G);
exo_grid_min_median = splitapply(@median, raw.exo_grid_min, G);
exo_grid_max_median = splitapply(@median, raw.exo_grid_max, G);
exo_frac_clipped_mean = splitapply(@mean, raw.exo_frac_clipped, G);

rej_1pct = splitapply(@(x) mean(x, 'omitnan'), raw.reject_1pct, G);
rej_5pct = splitapply(@(x) mean(x, 'omitnan'), raw.reject_5pct, G);
rej_10pct = splitapply(@(x) mean(x, 'omitnan'), raw.reject_10pct, G);
se_1pct = sqrt(rej_1pct .* (1 - rej_1pct) ./ valid_tests);
se_5pct = sqrt(rej_5pct .* (1 - rej_5pct) ./ valid_tests);
se_10pct = sqrt(rej_10pct .* (1 - rej_10pct) ./ valid_tests);

summary = table(Tval, horizon_days, B, valid_tests, region, testType, role, ...
    lambda_mode, lambda_median, lambda_p25, lambda_p75, ...
    lambda_lower_bound_freq, lambda_upper_bound_freq, lambda_inference_median, lambda_fit_median, ...
    lambda_fit_lower_bound_freq, lambda_fit_upper_bound_freq, ...
    lambda_changed_freq, lambda_ratio_median, cv_mean_loss, ...
    ls_endo_rule, ls_endo, ls_exo_rule, ls_exo_median, ls_exo_p25, ls_exo_p75, ...
    exo_grid_type, exo_grid_min_median, exo_grid_max_median, exo_mode, ...
    exo_frac_clipped_mean, covariance_rule, covariance_type, covariance_bandwidth, ...
    covariance_bandwidth_rule, winsor_margin, ...
    rej_1pct, se_1pct, rej_5pct, se_5pct, rej_10pct, se_10pct, ...
    'VariableNames', {'Tval', 'horizon_days', 'B', 'valid_tests', ...
    'region', 'testType', 'role', 'lambda_mode', 'lambda_median', ...
    'lambda_p25', 'lambda_p75', 'lambda_lower_bound_freq', ...
    'lambda_upper_bound_freq', 'lambda_inference_median', 'lambda_fit_median', ...
    'lambda_fit_lower_bound_freq', 'lambda_fit_upper_bound_freq', ...
    'lambda_changed_freq', 'lambda_ratio_median', 'cv_mean_loss', ...
    'ls_endo_rule', 'ls_endo', ...
    'ls_exo_rule', 'ls_exo_median', 'ls_exo_p25', 'ls_exo_p75', ...
    'exo_grid_type', 'exo_grid_min_median', 'exo_grid_max_median', ...
    'exo_mode', 'exo_frac_clipped_mean', 'covariance_rule', ...
    'covariance_type', 'covariance_bandwidth', 'covariance_bandwidth_rule', ...
    'winsor_margin', 'rej_1pct', 'se_1pct', 'rej_5pct', 'se_5pct', ...
    'rej_10pct', 'se_10pct'});

summary = sortrows(summary, {'Tval', 'testType', 'region'});

end
