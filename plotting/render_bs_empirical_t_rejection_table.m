function tbl = render_bs_empirical_t_rejection_table(lambdaMethod)
%% Build Table IA.C.4 (BS rejection frequencies at empirical sample sizes).
%
% Reads saved bs_empirical_t rejection summaries only (no simulation,
% fitting or inference). Values are 5% rejection frequencies in percent for
% each restriction and region, with one column per maturity.
%
% Sources, under simulation_output_dir('simulations', lambdaMethod)/bs_empirical_t/:
%   bs_results.mat              a four-maturity run (CV), or
%   bs_results_<horizon>.mat    one file per maturity (eff_dim production runs
%                               one maturity per call).
% A maturity with no saved results is NOT filled in: its column is reported
% as not run, and the outputs are written as
%   bs_empirical_t_rejection_table_partial.{csv,tex}
% with the missing maturities named in the file, so an incomplete table is
% never labeled as the four-maturity experiment. With all four maturities
% the outputs are bs_empirical_t_rejection_table.{csv,tex}.
%
% lambdaMethod: 'eff_dim' (default, get_frozen_design().
% simulation_lambda_method) or 'cv'. Outputs go to
% simulation_output_dir('figures', lambdaMethod)/bs_empirical_t/.

setpath();
if nargin < 1 || isempty(lambdaMethod)
    lambdaMethod = get_frozen_design().simulation_lambda_method;
end

horizons = ["quarterly","monthly","weekly","daily"];
tests = ["mono","conv","conc"];
testLabels = ["Monotonicity","Convexity","Concavity"];
regions = ["left","center","right"];
regionLabels = ["OTM put","Near ATM","OTM call"];
Bdesign = get_experiment_design('bs_empirical_t', 'monthly').B;

simDir = fullfile(simulation_output_dir('simulations', lambdaMethod), 'bs_empirical_t');
fullFile = fullfile(simDir, 'bs_results.mat');
summaries = cell(1, numel(horizons));
sources = strings(1, numel(horizons));
Bsaved = NaN(1, numel(horizons));
if isfile(fullFile)
    S = load(fullFile, 'rejection_summary', 'Btotal');
    for ih = 1:numel(horizons)
        R = S.rejection_summary(string(S.rejection_summary.horizon) == horizons(ih), :);
        if ~isempty(R), summaries{ih} = R; sources(ih) = fullFile; Bsaved(ih) = S.Btotal; end
    end
end
for ih = 1:numel(horizons)
    f = fullfile(simDir, sprintf('bs_results_%s.mat', horizons(ih)));
    if ~isfile(f), continue; end
    assert(isempty(summaries{ih}), ...
        'Both %s and %s hold %s results; keep one source per maturity.', fullFile, f, horizons(ih));
    S = load(f, 'rejection_summary', 'Btotal');
    summaries{ih} = S.rejection_summary;
    sources(ih) = f;
    Bsaved(ih) = S.Btotal;
end
available = ~cellfun(@isempty, summaries);
assert(any(available), 'No saved bs_empirical_t results under %s.', simDir);

nRow = numel(tests) * numel(regions);
restriction = strings(nRow, 1); region = strings(nRow, 1);
vals = NaN(nRow, numel(horizons)); Tcols = NaN(1, numel(horizons));
k = 0;
for it = 1:numel(tests)
    for ir = 1:numel(regions)
        k = k + 1;
        restriction(k) = testLabels(it);
        region(k) = regionLabels(ir);
        for ih = find(available)
            R = summaries{ih};
            idx = string(R.horizon) == horizons(ih) & string(R.testType) == tests(it) ...
                & string(R.region) == regions(ir);
            assert(nnz(idx) == 1, 'Expected one summary row for %s/%s/%s.', ...
                horizons(ih), tests(it), regions(ir));
            assert(R.B(idx) == Bsaved(ih), '%s/%s/%s summarizes B = %d of the %d saved replications.', ...
                horizons(ih), tests(it), regions(ir), R.B(idx), Bsaved(ih));
            vals(k, ih) = 100 * R.rej_5pct(idx);
            Tcols(ih) = R.Tval(idx);
        end
    end
end

colNames = strings(1, numel(horizons));
for ih = 1:numel(horizons)
    if available(ih), colNames(ih) = sprintf('%s_T%d', horizons(ih), Tcols(ih));
    else, colNames(ih) = sprintf('%s_not_run', horizons(ih)); end
end
tbl = [table(restriction, region), array2table(vals, 'VariableNames', cellstr(colNames))];

missing = horizons(~available);
if isempty(missing)
    stem = 'bs_empirical_t_rejection_table';
    status = 'complete: all four maturities';
else
    stem = 'bs_empirical_t_rejection_table_partial';
    status = sprintf('PARTIAL: %s not run; this is not the four-maturity table', strjoin(missing, ', '));
end
if any(Bsaved(available) ~= Bdesign)
    stem = [stem '_nonproduction'];
    status = sprintf('%s; NON-PRODUCTION: B = %s, not the design B = %d', status, ...
        mat2str(Bsaved(available)), Bdesign);
end
tbl.Properties.Description = status;

outDir = fullfile(simulation_output_dir('figures', lambdaMethod), 'bs_empirical_t');
if ~isfolder(outDir), mkdir(outDir); end
writetable(tbl, fullfile(outDir, [stem '.csv']));

fid = fopen(fullfile(outDir, [stem '.tex']), 'w');
cleaner = onCleanup(@() fclose(fid));
fprintf(fid, '%% Generated by render_bs_empirical_t_rejection_table (%s); B per reported column: %s.\n', ...
    lambdaMethod, mat2str(Bsaved(available)));
fprintf(fid, '%% Table status: %s.\n', status);
for ih = 1:numel(horizons)
    fprintf(fid, '%% %s: %s\n', horizons(ih), ternary(available(ih), sources(ih), "not run"));
end
k = 0;
cells = compose('%.2f\\%%', vals);
cells(isnan(vals)) = {'n.a.'};
for it = 1:numel(tests)
    fprintf(fid, '\\multirow{3}{*}{\\textbf{%s}}\n', testLabels(it));
    for ir = 1:numel(regions)
        k = k + 1;
        fprintf(fid, '& %s & %s \\\\\n', regionLabels(ir), strjoin(cells(k, :), ' & '));
    end
end

fprintf('Table IA.C.4 (%s) -- %s\n', lambdaMethod, status);
disp(tbl);

end

function out = ternary(cond, a, b)
if cond, out = a; else, out = b; end
end
