function design = get_bs_study_design()
%% Return the Black--Scholes study design manifest (both experiments).

final = get_frozen_design();
horizons = final.bs_empirical_t.horizons;
n = numel(final.bs_increasing_t.T) + numel(horizons);
rows = cell(n,1);
row = 0;

cfgA = config_bs_simulation_design('monthly','bs_increasing_t');
for j = 1:numel(final.bs_increasing_t.T)
    row = row + 1;
    rows{row} = one_row(row, "monthly_performance", cfgA, ...
        final.bs_increasing_t.T(j), cfgA.sim.seed0 + 1000000*(row-1));
end

for j = 1:numel(horizons)
    row = row + 1;
    cfgB = config_bs_simulation_design(horizons(j),'bs_empirical_t');
    rows{row} = one_row(row, "empirical_T", cfgB, cfgB.sim.empirical_T, ...
        cfgA.sim.seed0 + 1000000*(row-1));
end

design = cat(1,rows{:});

end

function out = one_row(id, group, cfg, Tval, seed0)
%% Convert one configured BS experiment into a manifest row.

strike = cfg.sim.strike_design;
out = table(id, string(group), string(cfg.sim.experiment), string(cfg.sim.horizon), ...
    Tval, cfg.bs.dt, cfg.training.cv.min_train_dates, cfg.sim.J, ...
    string(cfg.sim.option_grid_type), cfg.sim.m_min, cfg.sim.m_max, ...
    {cfg.sim.option_m_grid(:)}, string(mat2str(cfg.sim.option_m_grid(:).',17)), ...
    strike.median_count_before_rounding, string(strike.source_file), ...
    cfg.training.n_m_grid, string(cfg.training.mon_grid_type), ...
    cfg.testing.grid.n_points, string(cfg.testing.grid.type), ...
    cfg.testing.regionSpecs(1).bounds(2), cfg.testing.regionSpecs(2).bounds(2), ...
    string(cfg.testing.hac_bandwidth_rule), bartlett_hac_bandwidth(Tval), ...
    string(cfg.testing.inference_lambda.rule), seed0, string(cfg.revision.id), ...
    'VariableNames', {'design_id','design_group','experiment','horizon','Tval', ...
    'maturity_years','cv_min_train_dates','option_panel_m_points', ...
    'option_panel_m_grid_type','option_panel_m_min','option_panel_m_max', ...
    'option_m_grid','option_m_grid_text','median_empirical_strike_count', ...
    'strike_source_file','n_m_grid','mon_grid_type','test_grid_n_points', ...
    'test_grid_type','left_center_cutoff','center_right_cutoff', ...
    'hac_bandwidth_rule','hac_bandwidth','inference_lambda_rule', ...
    'seed0','revision_id'});

end
