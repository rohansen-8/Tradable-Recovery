function maturity = get_empirical_maturity_config(horizon)
%% Return the per-maturity domains, regions, and figure ranges.
%
% Three distinct forward-moneyness objects are configured here and must never
% be conflated:
%   estimator_domain : 30-point RKHS basis support, fixed per maturity
%                      (plus the separate reference point m = 1);
%   support_domain   : empirical 20%-date-coverage option support, derived
%                      from the active data/<maturity>/df.csv panel by one
%                      deterministic, interpolation-free rule: with
%                      k = ceil(0.2*T),
%                        support_lo = k-th smallest per-date minimum
%                        support_hi = k-th largest  per-date maximum
%                      of frwd_moneyness. The constants below are that exact
%                      computation on the active panels;
%                      verify_supported_testing_domain re-derives them and
%                      requires exact equality;
%   test_domain      : formal shape-test domain, the intersection of the
%                      figure domain exp(figure_log_range)
%                      with support_domain.
% Observed option locations are a fourth object (the data) and equal none of
% the above.

horizons = ["quarterly"; "monthly"; "weekly"; "daily"];
T = [97; 273; 694; 1964];
supportDomains = [ ...
    0.56147167769263,   1.18831169511829; ...
    0.744456334784572,  1.09089309666474; ...
    0.917587749971634,  1.03688696897526; ...
    0.967264263145474,  1.0208603191431];
estimatorDomains = [ ...
    0.7, 1.4; ...
    0.7, 1.3; ...
    0.7, 1.3; ...
    0.8, 1.2];
% Exogenous (VIX) basis support: fixed [5,65] except weekly, where the
% estimation panel's min/max VIX is used.
exoRanges = {[5 65]; [5 65]; []; [5 65]};
figureLogRanges = [ ...
    -0.25, 0.25; ...
    -0.30, 0.15; ...
    -0.20, 0.10; ...
    -0.10, 0.10];
regionCutoffs = [ ...
    0.880, 1.030; ...
    0.920, 1.030; ...
    0.945, 1.000; ...
    0.970, 1.010];

horizon = validatestring(char(string(horizon)), cellstr(horizons), ...
    mfilename, 'horizon');
idx = find(horizons == string(horizon), 1);

maturity = struct();
maturity.horizon = char(horizons(idx));
maturity.T = T(idx);
maturity.support_domain = supportDomains(idx,:);
maturity.estimator_domain = estimatorDomains(idx,:);
maturity.exo_range = exoRanges{idx};
maturity.exo_range_is_data_driven = isempty(exoRanges{idx});
maturity.figure_log_range = figureLogRanges(idx,:);
maturity.test_domain = [ ...
    max(exp(figureLogRanges(idx,1)), supportDomains(idx,1)), ...
    min(exp(figureLogRanges(idx,2)), supportDomains(idx,2))];
maturity.region_cutoffs = regionCutoffs(idx,:);
maturity.region_bounds = [ ...
    maturity.test_domain(1), maturity.region_cutoffs(1); ...
    maturity.region_cutoffs(1), maturity.region_cutoffs(2); ...
    maturity.region_cutoffs(2), maturity.test_domain(2)];
maturity.support_domain_source = ...
    'active_panel_order_statistic_20pct_dates';
maturity.estimator_domain_source = 'coauthor_python_config_moneyness_range';
maturity.test_domain_source = 'figure_domain_intersect_20pct_support';

assert(maturity.test_domain(1) < maturity.region_cutoffs(1) && ...
    maturity.region_cutoffs(2) < maturity.test_domain(2), ...
    '%s region cutoffs must lie strictly inside the test domain.', horizon);
assert(maturity.estimator_domain(1) <= maturity.test_domain(1) && ...
    maturity.test_domain(2) <= maturity.estimator_domain(2), ...
    '%s test domain must lie inside the estimator basis domain.', horizon);

end
